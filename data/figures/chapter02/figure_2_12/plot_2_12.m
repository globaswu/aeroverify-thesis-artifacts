function metrics = plot_2_12(outputPath)
%REPRODUCE_LIFT_COMPARISON Plot adjacent CSV data without any solver calls.
% The reference is reconstructed from the reported experimental Table I
% slope and zero-lift angle in Sivells (1947), NACA TN 1422. It is not a
% set of measured discrete points. No MAT, F06, or private path is required.

outDir = fileparts(mfilename('fullpath'));
if nargin < 1, outputPath = fullfile(outDir,'figure_2_12.png'); end
[outputFolder,~,~] = fileparts(outputPath);
if ~isempty(outputFolder) && ~isfolder(outputFolder), mkdir(outputFolder); end
T = readtable(fullfile(outDir, 'figure_2_12.csv'));
alpha = T.alpha_deg;
assert(isequal(alpha, (-2:2:8).'), 'Expected six samples from -2 to 8 deg.');
assert(isscalar(unique(T.reference_slope_per_deg)), ...
    'Reference slope must be constant.');
assert(isscalar(unique(T.reference_zero_lift_deg)), ...
    'Reference zero-lift angle must be constant.');
referenceSlope = T.reference_slope_per_deg(1);
referenceZero = T.reference_zero_lift_deg(1);
denseAlpha = linspace(alpha(1), alpha(end), 501).';
reference = referenceSlope .* (denseAlpha - referenceZero);

fig = figure('Visible', 'off', 'Color', 'w', 'Units', 'inches', ...
    'Position', [1 1 7.087 4.75], 'PaperPositionMode', 'auto');
cleanup = onCleanup(@() close(fig));
ax = axes(fig, 'Units', 'normalized', 'Position', [0.12 0.145 0.855 0.685]);
hold(ax, 'on');
hReference = plot(ax, denseAlpha, reference, '--', 'Color', [0.2 0.2 0.2], ...
    'LineWidth', 1.55);
hNastran = plot(ax, alpha, T.CL_Nastran, '-s', ...
    'Color', [33 102 172]/255, 'LineWidth', 1.55, ...
    'MarkerSize', 5.6, 'MarkerFaceColor', 'w');
hLLT = plot(ax, alpha, T.CL_LLT, '-.^', ...
    'Color', [198 107 24]/255, 'LineWidth', 1.55, ...
    'MarkerSize', 6, 'MarkerFaceColor', 'w');
set(ax, 'FontName', 'Times New Roman', 'FontSize', 10, ...
    'LineWidth', 0.8, 'TickDir', 'out', 'Box', 'on', ...
    'XLim', [-2.25 8.25], 'YLim', [-0.12 0.94], ...
    'XTick', alpha, 'YTick', 0:0.2:0.8, ...
    'GridColor', [0.75 0.75 0.75], 'GridAlpha', 0.45);
grid(ax, 'on');
yline(ax, 0, '-', 'Color', [0.66 0.66 0.66], ...
    'LineWidth', 0.7, 'HandleVisibility', 'off');
xlabel(ax, 'Root-chord incidence, \alpha (deg)', ...
    'FontName', 'Times New Roman', 'FontSize', 11);
ylabel(ax, 'Wing lift coefficient, C_L', ...
    'FontName', 'Times New Roman', 'FontSize', 11);
lgd = legend(ax, [hReference hNastran hLLT], ...
    {'Sivells (1947), Table I: linear reconstruction', ...
     'Nastran SOL 144', 'Lifting-line calculation'}, ...
    'Location', 'northwest', 'FontName', 'Times New Roman', ...
    'FontSize', 9.5, 'Box', 'off');
lgd.Color = 'w';
annotation(fig, 'textbox', [0.12 0.902 0.855 0.07], ...
    'String', 'Lift comparison for the NACA 65-210 wing', ...
    'LineStyle', 'none', 'Margin', 0, 'FontName', 'Times New Roman', ...
    'FontSize', 12.5, 'VerticalAlignment', 'middle');
annotation(fig, 'textbox', [0.12 0.848 0.855 0.05], ...
    'String', 'Retained calculations and a linear reference from experimental parameters', ...
    'LineStyle', 'none', 'Margin', 0, 'FontName', 'Times New Roman', ...
    'FontSize', 9.8, 'Color', [0.31 0.31 0.31], ...
    'VerticalAlignment', 'middle');
print(fig, outputPath, '-dpng', '-r600');

series = ["Nastran SOL 144"; "Lifting-line calculation"];
values = [T.CL_Nastran T.CL_LLT];
slopes = zeros(2, 1);
intercepts = zeros(2, 1);
crossings = zeros(2, 1);
for k = 1:2
    fitted = polyfit(alpha, values(:, k), 1);
    slopes(k) = fitted(1);
    intercepts(k) = fitted(2);
    index = find(values(1:end-1, k) <= 0 & values(2:end, k) >= 0, 1);
    assert(~isempty(index), 'No bracketed zero-lift crossing.');
    crossings(k) = alpha(index) - values(index, k) * ...
        (alpha(index+1)-alpha(index)) / (values(index+1, k)-values(index, k));
end
metrics = table(series, slopes, intercepts, -intercepts./slopes, crossings, ...
    100*(slopes/referenceSlope-1), -intercepts./slopes-referenceZero, ...
    'VariableNames', {'series', 'slope_per_deg', 'fitted_CL_at_zero', ...
    'fitted_zero_lift_deg', 'bracketed_zero_lift_deg', ...
    'slope_difference_percent', 'fitted_zero_lift_difference_deg'});
disp(metrics);
end
