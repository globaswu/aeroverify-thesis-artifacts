function plot_material_distribution(outputFile)
% Reproduce the two-panel Chapter 6 figure using only the adjacent CSV.
% Add this directory to the path, then call plot_material_distribution(outputFile).
% No solver is called; the provided output file may be outside this bundle.
if nargin < 1
    outputFile = fullfile(pwd, 'coupled_member_grading_mass.png');
end
figureFolder = fileparts(mfilename('fullpath'));
figureData = readtable(fullfile(figureFolder, 'selected_material_distribution.csv'), ...
    'TextType', 'string');
assert(isequal(figureData.Case(:).', [4 37 64 99]));
assert(all(abs(figureData.SkinMassTwoWing_kg + ...
    figureData.LatticeMassTwoWing_kg - figureData.TotalMassTwoWing_kg) < 1e-9));
assert(all(figureData.RootDiameter_mm > figureData.TipDiameter_mm));

caseColors = [0.16 0.16 0.16; 0.086 0.486 0.714; ...
    0.396 0.486 0.153; 0.863 0.478 0.094];
caseStyles = {'-', '--', '-.', ':'};
caseMarkers = {'o', 's', '^', 'd'};
caseNames = {'4 (initial)', '37 (adaptive)', '64 (adaptive)', '99 (adaptive)'};
figureHandle = figure('Visible', 'off', 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2 2 19 10.6]);
axesDiameter = axes(figureHandle, 'Position', [0.086 0.23 0.390 0.59]);
axesMass = axes(figureHandle, 'Position', [0.568 0.23 0.380 0.59]);
axesHandles = [axesDiameter axesMass];
for axisIndex = 1:2
    set(axesHandles(axisIndex), 'FontName', 'Times New Roman', ...
        'FontSize', 10, 'Box', 'off', 'TickDir', 'out', ...
        'LineWidth', 0.65, 'XColor', [0.16 0.16 0.16], ...
        'YColor', [0.16 0.16 0.16], 'YGrid', 'on', ...
        'GridColor', [0.6 0.6 0.6], 'GridAlpha', 0.18, ...
        'Layer', 'top');
    hold(axesHandles(axisIndex), 'on');
end

eta = linspace(0, 1, 101);
lineHandles = gobjects(4, 1);
for caseIndex = 1:4
    diameter = figureData.RootDiameter_mm(caseIndex) + eta .* ...
        (figureData.TipDiameter_mm(caseIndex) - figureData.RootDiameter_mm(caseIndex));
    lineHandles(caseIndex) = line(axesDiameter, eta, diameter, ...
        'Color', caseColors(caseIndex, :), 'LineStyle', caseStyles{caseIndex}, ...
        'LineWidth', 1.65, 'DisplayName', caseNames{caseIndex});
    line(axesDiameter, [0 1], diameter([1 end]), 'LineStyle', 'none', ...
        'Color', caseColors(caseIndex, :), 'Marker', caseMarkers{caseIndex}, ...
        'MarkerSize', 4.3, 'MarkerFaceColor', 'w', 'LineWidth', 1.0, ...
        'HandleVisibility', 'off', 'Clipping', 'off');
end
xlim(axesDiameter, [0 1]); ylim(axesDiameter, [0 10]);
xticks(axesDiameter, 0:0.25:1); yticks(axesDiameter, 0:2:10);
xlabel(axesDiameter, 'Normalized semispan, \eta = y/s');
ylabel(axesDiameter, 'Nominal diameter [mm]');
titleDiameter = title(axesDiameter, '(a) Prescribed member grading', ...
    'FontWeight', 'normal', 'FontSize', 11);
titleDiameter.Units = 'normalized'; titleDiameter.Position = [0.5 1.075 0];
caseLegend = legend(axesDiameter, lineHandles, caseNames, 'NumColumns', 4, ...
    'Orientation', 'horizontal', 'Box', 'off', 'FontSize', 9.3);
caseLegend.Units = 'normalized';
caseLegend.Position = [0.075 0.905 0.88 0.055];

barWidth = 0.62;
for caseIndex = 1:4
    skin = figureData.SkinMassTwoWing_kg(caseIndex);
    lattice = figureData.LatticeMassTwoWing_kg(caseIndex);
    rectangle(axesMass, 'Position', [caseIndex-barWidth/2 0 barWidth skin], ...
        'FaceColor', 'w', 'EdgeColor', caseColors(caseIndex, :), 'LineWidth', 1.2);
    rectangle(axesMass, 'Position', [caseIndex-barWidth/2 skin barWidth lattice], ...
        'FaceColor', caseColors(caseIndex, :), ...
        'EdgeColor', caseColors(caseIndex, :), 'LineWidth', 1.2);
    text(axesMass, caseIndex, skin/2, sprintf('%.2f', skin), ...
        'HorizontalAlignment', 'center', 'FontName', 'Times New Roman', ...
        'FontSize', 9, 'Color', [0.2 0.2 0.2]);
    text(axesMass, caseIndex, figureData.TotalMassTwoWing_kg(caseIndex)+2.6, ...
        sprintf('%.2f', figureData.TotalMassTwoWing_kg(caseIndex)), ...
        'HorizontalAlignment', 'center', 'VerticalAlignment', 'bottom', ...
        'FontName', 'Times New Roman', 'FontSize', 9.3);
end
skinKey = patch(axesMass, nan, nan, 'w', 'EdgeColor', [0.25 0.25 0.25], 'LineWidth', 1);
latticeKey = patch(axesMass, nan, nan, [0.3 0.3 0.3], 'EdgeColor', [0.25 0.25 0.25]);
massLegend = legend(axesMass, [skinKey latticeKey], {'Skin', 'Implicit lattice'}, ...
    'Location', 'northeast', 'Box', 'off', 'FontSize', 9.3);
massLegend.ItemTokenSize = [14 10];
xlim(axesMass, [0.4 4.6]); ylim(axesMass, [0 115]);
xticks(axesMass, 1:4); xticklabels(axesMass, string(figureData.Case));
yticks(axesMass, 0:20:100);
xlabel(axesMass, 'Case'); ylabel(axesMass, 'Two-wing optimization mass [kg]');
titleMass = title(axesMass, '(b) Skin and lattice mass', ...
    'FontWeight', 'normal', 'FontSize', 11);
titleMass.Units = 'normalized'; titleMass.Position = [0.5 1.075 0];

annotation(figureHandle, 'textbox', [0.07 0.015 0.89 0.105], ...
    'String', {'Prescribed linear law: t(\eta) = t_1 + (t_2 - t_1)\eta; evaluated endpoint parameters.', ...
    'Mass labels show skin contributions and totals; lattice mass uses the implicit geometry.'}, ...
    'Interpreter', 'tex', 'FontName', 'Times New Roman', 'FontSize', 9, ...
    'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
    'EdgeColor', 'none', 'FitBoxToText', 'off');
drawnow;
set(figureHandle, 'PaperPositionMode', 'auto');
print(figureHandle, outputFile, '-dpng', '-r600');
close(figureHandle);
fprintf('Saved %s at 600 dpi.\n', outputFile);
end
